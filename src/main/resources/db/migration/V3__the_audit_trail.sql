-- the audit trail

CREATE TABLE audit_entries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    happened_at TIMESTAMP(6) NOT NULL,
    actor CHARACTER VARYING(128) NOT NULL,
    action CHARACTER VARYING(32) NOT NULL,
    subject_kind CHARACTER VARYING(32) NOT NULL,
    subject_id CHARACTER VARYING(32) NOT NULL,
    detail CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_audit_entries PRIMARY KEY (id),
    CONSTRAINT ck_audit_entries_action_named CHECK (action <> ''),
    CONSTRAINT ck_audit_entries_actor_named CHECK (actor <> '')
);

CREATE INDEX ix_audit_entries_happened_at ON audit_entries (happened_at);

CREATE INDEX ix_audit_entries_subject ON audit_entries (subject_kind, subject_id);
