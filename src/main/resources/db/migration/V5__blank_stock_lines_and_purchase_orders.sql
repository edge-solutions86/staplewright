-- blank stock lines and purchase orders

CREATE TABLE blank_purchase_orders (
    number CHARACTER VARYING(32) NOT NULL,
    supplier CHARACTER VARYING(128) NOT NULL,
    placed_on DATE NOT NULL,
    state CHARACTER VARYING(32) NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_blank_purchase_orders PRIMARY KEY (number),
    CONSTRAINT ck_blank_purchase_orders_order_state_is_known CHECK (state in ('placed', 'part received', 'received', 'cancelled'))
);

CREATE TABLE blank_purchase_lines (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    order_number CHARACTER VARYING(32) NOT NULL,
    part_number CHARACTER VARYING(32) NOT NULL,
    ordered INTEGER NOT NULL,
    received INTEGER NOT NULL,
    CONSTRAINT pk_blank_purchase_lines PRIMARY KEY (id),
    CONSTRAINT fk_blank_purchase_lines_order_number_blank_purchase_orders FOREIGN KEY (order_number) REFERENCES blank_purchase_orders (number) ON DELETE CASCADE,
    CONSTRAINT fk_blank_purchase_lines_part_number_key_blanks FOREIGN KEY (part_number) REFERENCES key_blanks (part_number) ON DELETE RESTRICT,
    CONSTRAINT ck_blank_purchase_lines_ordered_positive CHECK (ordered > 0),
    CONSTRAINT ck_blank_purchase_lines_not_more_than_ordered CHECK (received <= ordered),
    CONSTRAINT ck_blank_purchase_lines_received_not_negative CHECK (received >= 0)
);

CREATE TABLE blank_stock_lines (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    part_number CHARACTER VARYING(32) NOT NULL,
    movement CHARACTER VARYING(32) NOT NULL,
    quantity INTEGER NOT NULL,
    moved_on DATE NOT NULL,
    reference CHARACTER VARYING(32) NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_blank_stock_lines PRIMARY KEY (id),
    CONSTRAINT fk_blank_stock_lines_part_number_key_blanks FOREIGN KEY (part_number) REFERENCES key_blanks (part_number) ON DELETE RESTRICT,
    CONSTRAINT ck_blank_stock_lines_a_scrapping_says_why CHECK (movement <> 'scrapped' or note <> ''),
    CONSTRAINT ck_blank_stock_lines_movement_is_known CHECK (movement in ('received', 'cut', 'scrapped', 'returned', 'counted')),
    CONSTRAINT ck_blank_stock_lines_quantity_positive CHECK (quantity > 0)
);

CREATE INDEX ix_blank_stock_lines_part_day ON blank_stock_lines (part_number, moved_on);
