-- lockout calls and hardware surveys

CREATE TABLE surveys (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    building_code CHARACTER VARYING(32) NOT NULL,
    walked_on DATE NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_surveys PRIMARY KEY (id),
    CONSTRAINT uq_surveys_building_code_walked_on UNIQUE (building_code, walked_on),
    CONSTRAINT fk_surveys_building_code_buildings FOREIGN KEY (building_code) REFERENCES buildings (code) ON DELETE RESTRICT
);

CREATE TABLE lockouts (
    number CHARACTER VARYING(32) NOT NULL,
    opening_number CHARACTER VARYING(32) NOT NULL,
    keyholder CHARACTER VARYING(32) NOT NULL,
    called_at TIMESTAMP(6) NOT NULL,
    state CHARACTER VARYING(32) NOT NULL,
    attended_at TIMESTAMP(6),
    closed_at TIMESTAMP(6),
    technician CHARACTER VARYING(128) NOT NULL,
    identified_by CHARACTER VARYING(512) NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_lockouts PRIMARY KEY (number),
    CONSTRAINT fk_lockouts_opening_number_openings FOREIGN KEY (opening_number) REFERENCES openings (number) ON DELETE RESTRICT,
    CONSTRAINT ck_lockouts_attended_has_a_technician CHECK (state <> 'attended' or technician <> ''),
    CONSTRAINT ck_lockouts_attended_after_called CHECK (attended_at is null or attended_at >= called_at)
);

CREATE TABLE survey_lines (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    survey_id INTEGER NOT NULL,
    opening_number CHARACTER VARYING(32) NOT NULL,
    surveyor CHARACTER VARYING(128) NOT NULL,
    condition INTEGER NOT NULL,
    manufacturer CHARACTER VARYING(128) NOT NULL,
    cylinder_serial CHARACTER VARYING(32) NOT NULL,
    deficiencies CHARACTER VARYING(512) NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_survey_lines PRIMARY KEY (id),
    CONSTRAINT uq_survey_lines_survey_id_opening_number UNIQUE (survey_id, opening_number),
    CONSTRAINT fk_survey_lines_opening_number_openings FOREIGN KEY (opening_number) REFERENCES openings (number) ON DELETE RESTRICT,
    CONSTRAINT fk_survey_lines_survey_id_surveys FOREIGN KEY (survey_id) REFERENCES surveys (id) ON DELETE CASCADE,
    CONSTRAINT ck_survey_lines_condition_in_range CHECK (condition between 1 and 4)
);
