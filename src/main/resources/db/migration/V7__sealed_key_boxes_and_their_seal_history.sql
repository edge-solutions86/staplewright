-- sealed key boxes and their seal history

CREATE TABLE key_boxes (
    number CHARACTER VARYING(32) NOT NULL,
    building_code CHARACTER VARYING(32) NOT NULL,
    opening_number CHARACTER VARYING(32) NOT NULL,
    symbol CHARACTER VARYING(16) NOT NULL,
    seal CHARACTER VARYING(32) NOT NULL,
    sealed_on DATE NOT NULL,
    state CHARACTER VARYING(32) NOT NULL,
    checked_on DATE,
    opened_on DATE,
    opened_by CHARACTER VARYING(128) NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_key_boxes PRIMARY KEY (number),
    CONSTRAINT uq_key_boxes_opening_number UNIQUE (opening_number),
    CONSTRAINT fk_key_boxes_building_code_buildings FOREIGN KEY (building_code) REFERENCES buildings (code) ON DELETE RESTRICT,
    CONSTRAINT fk_key_boxes_opening_number_openings FOREIGN KEY (opening_number) REFERENCES openings (number) ON DELETE RESTRICT,
    CONSTRAINT ck_key_boxes_an_open_box_says_when CHECK (state <> 'opened' or opened_on is not null),
    CONSTRAINT ck_key_boxes_a_sealed_box_has_a_seal CHECK (state <> 'sealed' or seal <> ''),
    CONSTRAINT ck_key_boxes_box_state_is_known CHECK (state in ('sealed', 'opened', 'empty', 'withdrawn')),
    CONSTRAINT ck_key_boxes_checked_after_sealed CHECK (checked_on is null or checked_on >= sealed_on)
);

CREATE TABLE key_box_seals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    box_number CHARACTER VARYING(32) NOT NULL,
    seal CHARACTER VARYING(32) NOT NULL,
    symbol CHARACTER VARYING(16) NOT NULL,
    sealed_on DATE NOT NULL,
    broken_on DATE,
    broken_by CHARACTER VARYING(128) NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_key_box_seals PRIMARY KEY (id),
    CONSTRAINT uq_key_box_seals_box_number_seal_sealed_on UNIQUE (box_number, seal, sealed_on),
    CONSTRAINT fk_key_box_seals_box_number_key_boxes FOREIGN KEY (box_number) REFERENCES key_boxes (number) ON DELETE CASCADE,
    CONSTRAINT ck_key_box_seals_broken_after_sealed CHECK (broken_on is null or broken_on >= sealed_on)
);

CREATE INDEX ix_key_box_seals_box_day ON key_box_seals (box_number, sealed_on);
