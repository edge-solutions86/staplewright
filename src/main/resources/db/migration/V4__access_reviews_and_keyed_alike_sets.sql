-- access reviews and keyed alike sets

CREATE TABLE access_reviews (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    department CHARACTER VARYING(128) NOT NULL,
    opened_on DATE NOT NULL,
    due_on DATE NOT NULL,
    state CHARACTER VARYING(32) NOT NULL,
    closed_on DATE,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_access_reviews PRIMARY KEY (id),
    CONSTRAINT uq_access_reviews_department_opened_on UNIQUE (department, opened_on),
    CONSTRAINT ck_access_reviews_closed_has_a_date CHECK (state <> 'closed' or closed_on is not null),
    CONSTRAINT ck_access_reviews_due_after_opened CHECK (due_on >= opened_on)
);

CREATE TABLE keyed_alike_sets (
    name CHARACTER VARYING(128) NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_keyed_alike_sets PRIMARY KEY (name)
);

CREATE TABLE access_review_lines (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    review_id INTEGER NOT NULL,
    tag CHARACTER VARYING(32) NOT NULL,
    keyholder CHARACTER VARYING(32) NOT NULL,
    symbol CHARACTER VARYING(32) NOT NULL,
    answer CHARACTER VARYING(32) NOT NULL,
    answered_on DATE,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_access_review_lines PRIMARY KEY (id),
    CONSTRAINT uq_access_review_lines_review_id_tag UNIQUE (review_id, tag),
    CONSTRAINT fk_access_review_lines_review_id_access_reviews FOREIGN KEY (review_id) REFERENCES access_reviews (id) ON DELETE CASCADE,
    CONSTRAINT ck_access_review_lines_answered_has_a_date CHECK (answer = 'unanswered' or answered_on is not null)
);

CREATE TABLE keyed_alike_members (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    set_name CHARACTER VARYING(128) NOT NULL,
    opening_number CHARACTER VARYING(32) NOT NULL,
    CONSTRAINT pk_keyed_alike_members PRIMARY KEY (id),
    CONSTRAINT uq_keyed_alike_members_opening_number UNIQUE (opening_number),
    CONSTRAINT fk_keyed_alike_members_opening_number_openings FOREIGN KEY (opening_number) REFERENCES openings (number) ON DELETE RESTRICT,
    CONSTRAINT fk_keyed_alike_members_set_name_keyed_alike_sets FOREIGN KEY (set_name) REFERENCES keyed_alike_sets (name) ON DELETE CASCADE
);
