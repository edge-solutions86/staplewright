-- the schema as it stands

CREATE TABLE access_groups (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name CHARACTER VARYING(128) NOT NULL,
    department CHARACTER VARYING(128) NOT NULL,
    description CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_access_groups PRIMARY KEY (id),
    CONSTRAINT uq_access_groups_name UNIQUE (name)
);

CREATE TABLE buildings (
    code CHARACTER VARYING(32) NOT NULL,
    name CHARACTER VARYING(128) NOT NULL,
    year_built INTEGER,
    CONSTRAINT pk_buildings PRIMARY KEY (code),
    CONSTRAINT ck_buildings_year_plausible CHECK (year_built is null or year_built > 1850)
);

CREATE TABLE charts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    manufacturer CHARACTER VARYING(128) NOT NULL,
    family CHARACTER VARYING(128) NOT NULL,
    chambers INTEGER NOT NULL,
    depths CHARACTER VARYING(96) NOT NULL,
    root_mils INTEGER NOT NULL,
    increment_mils INTEGER NOT NULL,
    first_space_mils INTEGER NOT NULL,
    space_increment_mils INTEGER NOT NULL,
    macs INTEGER NOT NULL,
    gauged_from_tip BOOLEAN NOT NULL,
    depth_tolerance_mils INTEGER NOT NULL,
    notes CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_charts PRIMARY KEY (id),
    CONSTRAINT uq_charts_manufacturer_family UNIQUE (manufacturer, family),
    CONSTRAINT ck_charts_chambers_positive CHECK (chambers > 0),
    CONSTRAINT ck_charts_increment_positive CHECK (increment_mils > 0),
    CONSTRAINT ck_charts_macs_positive CHECK (macs > 0)
);

CREATE TABLE counters (
    name CHARACTER VARYING(32) NOT NULL,
    prefix CHARACTER VARYING(32) NOT NULL,
    width INTEGER NOT NULL,
    next_value INTEGER NOT NULL,
    CONSTRAINT pk_counters PRIMARY KEY (name),
    CONSTRAINT ck_counters_next_value_positive CHECK (next_value > 0)
);

CREATE TABLE incidents (
    number CHARACTER VARYING(32) NOT NULL,
    tag CHARACTER VARYING(32) NOT NULL,
    symbol CHARACTER VARYING(32) NOT NULL,
    cause CHARACTER VARYING(32) NOT NULL,
    reported_on DATE NOT NULL,
    keyholder CHARACTER VARYING(32) NOT NULL,
    severity CHARACTER VARYING(32) NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_incidents PRIMARY KEY (number),
    CONSTRAINT ck_incidents_theft_is_written_up CHECK (cause <> 'stolen' or length(note) > 0)
);

CREATE TABLE keyholders (
    identifier CHARACTER VARYING(32) NOT NULL,
    name CHARACTER VARYING(128) NOT NULL,
    affiliation CHARACTER VARYING(32) NOT NULL,
    department CHARACTER VARYING(128) NOT NULL,
    standing CHARACTER VARYING(32) NOT NULL,
    ends_on DATE,
    separated_on DATE,
    CONSTRAINT pk_keyholders PRIMARY KEY (identifier),
    CONSTRAINT ck_keyholders_separated_has_a_date CHECK (standing <> 'separated' or separated_on is not null)
);

CREATE TABLE keyway_sections (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    family_name CHARACTER VARYING(128) NOT NULL,
    code CHARACTER VARYING(32) NOT NULL,
    manufacturer CHARACTER VARYING(128) NOT NULL,
    restricted BOOLEAN NOT NULL,
    patent_expires DATE,
    parent_id INTEGER,
    CONSTRAINT pk_keyway_sections PRIMARY KEY (id),
    CONSTRAINT uq_keyway_sections_family_name_code UNIQUE (family_name, code),
    CONSTRAINT fk_keyway_sections_parent_id_keyway_sections FOREIGN KEY (parent_id) REFERENCES keyway_sections (id) ON DELETE RESTRICT,
    CONSTRAINT ck_keyway_sections_not_its_own_parent CHECK (parent_id is null or parent_id <> id)
);

CREATE TABLE retired_bittings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    bitting CHARACTER VARYING(48) NOT NULL,
    reason CHARACTER VARYING(32) NOT NULL,
    retired_on DATE NOT NULL,
    symbol CHARACTER VARYING(32) NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_retired_bittings PRIMARY KEY (id),
    CONSTRAINT uq_retired_bittings_bitting UNIQUE (bitting)
);

CREATE TABLE authorizers (
    identifier CHARACTER VARYING(32) NOT NULL,
    department CHARACTER VARYING(128) NOT NULL,
    buildings CHARACTER VARYING(512) NOT NULL,
    may_approve_masters BOOLEAN NOT NULL,
    CONSTRAINT pk_authorizers PRIMARY KEY (identifier),
    CONSTRAINT fk_authorizers_identifier_keyholders FOREIGN KEY (identifier) REFERENCES keyholders (identifier) ON DELETE CASCADE
);

CREATE TABLE issued_keys (
    tag CHARACTER VARYING(32) NOT NULL,
    symbol CHARACTER VARYING(32) NOT NULL,
    keyholder CHARACTER VARYING(32) NOT NULL,
    issued_on DATE NOT NULL,
    due_on DATE,
    deposit_cents INTEGER NOT NULL,
    state CHARACTER VARYING(32) NOT NULL,
    closed_on DATE,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_issued_keys PRIMARY KEY (tag),
    CONSTRAINT fk_issued_keys_keyholder_keyholders FOREIGN KEY (keyholder) REFERENCES keyholders (identifier) ON DELETE RESTRICT,
    CONSTRAINT ck_issued_keys_deposit_not_negative CHECK (deposit_cents >= 0),
    CONSTRAINT ck_issued_keys_due_after_issue CHECK (due_on is null or due_on >= issued_on)
);

CREATE TABLE key_blanks (
    part_number CHARACTER VARYING(32) NOT NULL,
    section_id INTEGER NOT NULL,
    manufacturer CHARACTER VARYING(128) NOT NULL,
    chambers INTEGER NOT NULL,
    stock INTEGER NOT NULL,
    restricted BOOLEAN NOT NULL,
    supplier CHARACTER VARYING(128) NOT NULL,
    reorder_at INTEGER NOT NULL,
    CONSTRAINT pk_key_blanks PRIMARY KEY (part_number),
    CONSTRAINT fk_key_blanks_section_id_keyway_sections FOREIGN KEY (section_id) REFERENCES keyway_sections (id) ON DELETE RESTRICT,
    CONSTRAINT ck_key_blanks_chambers_positive CHECK (chambers > 0),
    CONSTRAINT ck_key_blanks_reorder_not_negative CHECK (reorder_at >= 0),
    CONSTRAINT ck_key_blanks_stock_not_negative CHECK (stock >= 0)
);

CREATE TABLE key_requests (
    number CHARACTER VARYING(32) NOT NULL,
    keyholder CHARACTER VARYING(32) NOT NULL,
    symbol CHARACTER VARYING(32) NOT NULL,
    building CHARACTER VARYING(32) NOT NULL,
    reason CHARACTER VARYING(512) NOT NULL,
    raised_on DATE NOT NULL,
    state CHARACTER VARYING(32) NOT NULL,
    is_master BOOLEAN NOT NULL,
    decided_on DATE,
    decided_by CHARACTER VARYING(32) NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_key_requests PRIMARY KEY (number),
    CONSTRAINT fk_key_requests_keyholder_keyholders FOREIGN KEY (keyholder) REFERENCES keyholders (identifier) ON DELETE RESTRICT,
    CONSTRAINT ck_key_requests_decided_has_a_date CHECK (state not in ('approved', 'denied') or decided_on is not null)
);

CREATE TABLE keying_systems (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name CHARACTER VARYING(128) NOT NULL,
    chart_id INTEGER NOT NULL,
    family_name CHARACTER VARYING(128) NOT NULL,
    top_section CHARACTER VARYING(32) NOT NULL,
    progression_step INTEGER NOT NULL,
    archived BOOLEAN NOT NULL,
    opened_on DATE,
    notes CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_keying_systems PRIMARY KEY (id),
    CONSTRAINT uq_keying_systems_name UNIQUE (name),
    CONSTRAINT fk_keying_systems_chart_id_charts FOREIGN KEY (chart_id) REFERENCES charts (id) ON DELETE RESTRICT,
    CONSTRAINT ck_keying_systems_step_positive CHECK (progression_step > 0)
);

CREATE TABLE openings (
    number CHARACTER VARYING(32) NOT NULL,
    building_code CHARACTER VARYING(32) NOT NULL,
    floor CHARACTER VARYING(32) NOT NULL,
    room CHARACTER VARYING(32) NOT NULL,
    function CHARACTER VARYING(32) NOT NULL,
    exterior BOOLEAN NOT NULL,
    description CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_openings PRIMARY KEY (number),
    CONSTRAINT uq_openings_building_code_room_floor UNIQUE (building_code, room, floor),
    CONSTRAINT fk_openings_building_code_buildings FOREIGN KEY (building_code) REFERENCES buildings (code) ON DELETE RESTRICT
);

CREATE TABLE work_orders (
    number CHARACTER VARYING(32) NOT NULL,
    incident_number CHARACTER VARYING(32),
    state CHARACTER VARYING(32) NOT NULL,
    technician CHARACTER VARYING(128) NOT NULL,
    scheduled_for DATE,
    closed_on DATE,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_work_orders PRIMARY KEY (number),
    CONSTRAINT fk_work_orders_incident_number_incidents FOREIGN KEY (incident_number) REFERENCES incidents (number) ON DELETE SET NULL,
    CONSTRAINT ck_work_orders_scheduled_has_a_day CHECK (state <> 'scheduled' or scheduled_for is not null)
);

CREATE TABLE access_requirements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    group_id INTEGER NOT NULL,
    opening_number CHARACTER VARYING(32) NOT NULL,
    CONSTRAINT pk_access_requirements PRIMARY KEY (id),
    CONSTRAINT uq_access_requirements_group_id_opening_number UNIQUE (group_id, opening_number),
    CONSTRAINT fk_access_requirements_group_id_access_groups FOREIGN KEY (group_id) REFERENCES access_groups (id) ON DELETE CASCADE,
    CONSTRAINT fk_access_requirements_opening_number_openings FOREIGN KEY (opening_number) REFERENCES openings (number) ON DELETE CASCADE
);

CREATE TABLE deposit_lines (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tag CHARACTER VARYING(32) NOT NULL,
    keyholder CHARACTER VARYING(32) NOT NULL,
    kind CHARACTER VARYING(32) NOT NULL,
    cents INTEGER NOT NULL,
    happened_on DATE NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_deposit_lines PRIMARY KEY (id),
    CONSTRAINT fk_deposit_lines_tag_issued_keys FOREIGN KEY (tag) REFERENCES issued_keys (tag) ON DELETE RESTRICT,
    CONSTRAINT ck_deposit_lines_cents_positive CHECK (cents > 0)
);

CREATE TABLE keying_groups (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    system_id INTEGER NOT NULL,
    name CHARACTER VARYING(128) NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_keying_groups PRIMARY KEY (id),
    CONSTRAINT uq_keying_groups_system_id_name UNIQUE (system_id, name),
    CONSTRAINT fk_keying_groups_system_id_keying_systems FOREIGN KEY (system_id) REFERENCES keying_systems (id) ON DELETE CASCADE
);

CREATE TABLE schedule_entries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    system_id INTEGER NOT NULL,
    symbol CHARACTER VARYING(16) NOT NULL,
    section CHARACTER VARYING(32) NOT NULL,
    bitting CHARACTER VARYING(48),
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_schedule_entries PRIMARY KEY (id),
    CONSTRAINT uq_schedule_entries_system_id_bitting UNIQUE (system_id, bitting),
    CONSTRAINT uq_schedule_entries_system_id_symbol UNIQUE (system_id, symbol),
    CONSTRAINT fk_schedule_entries_system_id_keying_systems FOREIGN KEY (system_id) REFERENCES keying_systems (id) ON DELETE CASCADE
);

CREATE TABLE work_order_lines (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    order_number CHARACTER VARYING(32) NOT NULL,
    serial CHARACTER VARYING(32) NOT NULL,
    opening_number CHARACTER VARYING(32) NOT NULL,
    state CHARACTER VARYING(32) NOT NULL,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_work_order_lines PRIMARY KEY (id),
    CONSTRAINT uq_work_order_lines_order_number_serial UNIQUE (order_number, serial),
    CONSTRAINT fk_work_order_lines_order_number_work_orders FOREIGN KEY (order_number) REFERENCES work_orders (number) ON DELETE CASCADE
);

CREATE TABLE cylinders (
    serial CHARACTER VARYING(32) NOT NULL,
    format CHARACTER VARYING(32) NOT NULL,
    section CHARACTER VARYING(32) NOT NULL,
    chambers INTEGER NOT NULL,
    manufacturer CHARACTER VARYING(128) NOT NULL,
    spooled BOOLEAN NOT NULL,
    installed_at CHARACTER VARYING(32),
    position CHARACTER VARYING(32),
    group_id INTEGER,
    note CHARACTER VARYING(512) NOT NULL,
    CONSTRAINT pk_cylinders PRIMARY KEY (serial),
    CONSTRAINT uq_cylinders_installed_at_position UNIQUE (installed_at, position),
    CONSTRAINT fk_cylinders_group_id_keying_groups FOREIGN KEY (group_id) REFERENCES keying_groups (id) ON DELETE SET NULL,
    CONSTRAINT fk_cylinders_installed_at_openings FOREIGN KEY (installed_at) REFERENCES openings (number) ON DELETE RESTRICT,
    CONSTRAINT ck_cylinders_installed_has_a_position CHECK ((installed_at is null) = (position is null)),
    CONSTRAINT ck_cylinders_chambers_positive CHECK (chambers > 0)
);

CREATE TABLE keying_group_members (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    group_id INTEGER NOT NULL,
    symbol CHARACTER VARYING(16) NOT NULL,
    CONSTRAINT pk_keying_group_members PRIMARY KEY (id),
    CONSTRAINT uq_keying_group_members_group_id_symbol UNIQUE (group_id, symbol),
    CONSTRAINT fk_keying_group_members_group_id_keying_groups FOREIGN KEY (group_id) REFERENCES keying_groups (id) ON DELETE CASCADE
);
